import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { rollup } from "rollup";
import { dts } from "rollup-plugin-dts";

const rootDir = process.cwd();
const sourceTypesDir = path.join(rootDir, "types", "ethers-contracts");
const configDir = path.join(rootDir, "contract-typings");
const packageDir = path.join(configDir, "package");
const packageSourceDir = path.join(packageDir, "src");
const generatedDir = path.join(packageSourceDir, "generated");
const packageName = "@ufarm/evm-v2-types";

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, "utf8"));
}

function writeJson(filePath, value) {
  writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return listFilesRecursive(dir);
}

function listFilesRecursive(dir) {
  const result = [];
  for (const name of readdirSync(dir).sort()) {
    const fullPath = path.join(dir, name);
    if (statSync(fullPath).isDirectory()) {
      result.push(...listFilesRecursive(fullPath));
    } else {
      result.push(fullPath);
    }
  }
  return result;
}

function toPackageImport(filePath) {
  const relative = path
    .relative(packageSourceDir, filePath)
    .replaceAll(path.sep, "/");
  return `./${relative.replace(/\.ts$/, ".js")}`;
}

function exportName(filePath) {
  return path.basename(filePath, ".ts");
}

function shouldExportGeneratedFile(filePath) {
  const normalized = filePath.replaceAll(path.sep, "/");
  if (!normalized.endsWith(".ts")) return false;
  if (normalized.endsWith("/index.ts")) return false;
  if (normalized.includes("/contracts/mocks/")) return false;
  if (normalized.includes("/factories/contracts/mocks/")) return false;
  return true;
}

function buildEntrypoint() {
  const typeRoots = [
    path.join(generatedDir, "contracts"),
    path.join(generatedDir, "@openzeppelin"),
  ];
  const factoryRoots = [
    path.join(generatedDir, "factories", "contracts"),
    path.join(generatedDir, "factories", "@openzeppelin"),
  ];

  const typeExports = typeRoots
    .flatMap(listFiles)
    .filter(shouldExportGeneratedFile)
    .flatMap((filePath) => {
      const name = exportName(filePath);
      const packageImport = toPackageImport(filePath);
      return [
        `export type { ${name} } from "${packageImport}";`,
        `export type * as ${name}Types from "${packageImport}";`,
      ];
    });

  const factoryExports = factoryRoots
    .flatMap(listFiles)
    .filter(shouldExportGeneratedFile)
    .filter((filePath) => exportName(filePath).endsWith("__factory"))
    .map(
      (filePath) =>
        `export { ${exportName(filePath)} } from "${toPackageImport(
          filePath
        )}";`
    );

  return [
    "/* Autogenerated package entrypoint. Do not edit manually. */",
    ...typeExports,
    ...factoryExports,
    "",
  ].join("\n");
}

function npmDependencyRange(version) {
  return version.startsWith("^") ||
    version.startsWith("~") ||
    version.startsWith(">")
    ? version
    : `^${version}`;
}

if (!existsSync(path.join(sourceTypesDir, "index.ts"))) {
  throw new Error(
    "TypeChain output is missing. Run `npm run compile` before building the typings package."
  );
}

const rootPackage = readJson(path.join(rootDir, "package.json"));
const template = readJson(path.join(configDir, "package.template.json"));
const ethersVersion =
  rootPackage.dependencies?.ethers ?? rootPackage.devDependencies?.ethers;

rmSync(packageDir, { force: true, recursive: true });
mkdirSync(packageSourceDir, { recursive: true });
cpSync(sourceTypesDir, generatedDir, { recursive: true });

writeFileSync(path.join(packageSourceDir, "index.ts"), buildEntrypoint());
writeFileSync(
  path.join(packageDir, "README.md"),
  readFileSync(path.join(configDir, "README.md"), "utf8")
);
writeJson(path.join(packageDir, "package.json"), {
  ...template,
  name: packageName,
  version: rootPackage.version,
  peerDependencies: {
    ...template.peerDependencies,
    ...(ethersVersion === undefined
      ? {}
      : { ethers: npmDependencyRange(ethersVersion) }),
  },
});

const npx = process.platform === "win32" ? "npx.cmd" : "npx";
const result = spawnSync(
  npx,
  [
    "tsup",
    path.join("contract-typings", "package", "src", "index.ts"),
    "--format",
    "esm,cjs",
    "--out-dir",
    path.join("contract-typings", "package", "dist"),
    "--target",
    "es2022",
    "--tsconfig",
    path.join("contract-typings", "tsconfig.json"),
    "--external",
    "ethers",
    "--clean",
  ],
  {
    cwd: rootDir,
    stdio: "inherit",
  }
);

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const declarations = await rollup({
  input: path.join(packageSourceDir, "index.ts"),
  external: (id) => id === "ethers" || id.startsWith("ethers/"),
  plugins: [dts({ tsconfig: path.join(configDir, "tsconfig.json") })],
});
const declarationPath = path.join(packageDir, "dist", "index.d.ts");
await declarations.write({
  file: declarationPath,
  format: "es",
});
await declarations.close();
copyFileSync(declarationPath, path.join(packageDir, "dist", "index.d.cts"));

const importCheck = spawnSync(
  process.execPath,
  [
    "--input-type=module",
    "--eval",
    `const pkg = await import(${JSON.stringify(
      packageName
    )}); if (typeof pkg.UFarmVault__factory !== "function") process.exit(1);`,
  ],
  {
    cwd: packageDir,
    stdio: "inherit",
  }
);

if (importCheck.status !== 0) {
  throw new Error(
    `Failed to import ${packageName} through its ESM package export.`
  );
}

const requireCheck = spawnSync(
  process.execPath,
  [
    "--input-type=commonjs",
    "--eval",
    `const pkg = require(${JSON.stringify(
      packageName
    )}); if (typeof pkg.UFarmVault__factory !== "function") process.exit(1);`,
  ],
  {
    cwd: packageDir,
    stdio: "inherit",
  }
);

if (requireCheck.status !== 0) {
  throw new Error(
    `Failed to require ${packageName} through its CommonJS package export.`
  );
}

const typeCheck = spawnSync(
  npx,
  [
    "tsc",
    "--noEmit",
    "--project",
    path.join("contract-typings", "tsconfig.consumer-check.json"),
  ],
  {
    cwd: rootDir,
    stdio: "inherit",
  }
);

if (typeCheck.status !== 0) {
  throw new Error(`Failed to type-check ${packageName} package exports.`);
}

console.log(
  `Built ${packageName}@${rootPackage.version} in ${path.relative(
    rootDir,
    packageDir
  )}`
);
